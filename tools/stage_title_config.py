"""Stage an ingest of Tier-3 coverage into the checked-in per-title config.

`ingest_coverage_manifests.py` writes per-base seed files and content-validated
banks; the banks carry captured guest bytes and are ROM-derived, so they stay in
the git-ignored build area, while the *addresses* are the part worth checking in.
This copies the seed files into `re/config/` with the ROM hash and runner build
id stripped (dump fingerprints do not belong in the repo) and writes an index
that names every load base a bank must exist for.

    python tools/stage_title_config.py --ingest banks/coverage-ingest --title black
"""

import argparse
import json
import os
import re

STRIP = re.compile(r"^#.*(ROM SHA-1|Runner build)")


def sanitize(path):
    kept = []
    for line in open(path, encoding="utf-8").read().splitlines():
        if STRIP.match(line):
            continue
        kept.append(line)
    return "\n".join(kept).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ingest", required=True, help="ingest --out directory")
    parser.add_argument("--title", required=True, help="title id, e.g. black")
    parser.add_argument("--out", default="re/config")
    args = parser.parse_args()

    report = json.load(open(os.path.join(args.ingest, "ingest-report.json"),
                            encoding="utf-8"))
    seed_dir = os.path.join(args.out, args.title, "seeds")
    os.makedirs(seed_dir, exist_ok=True)

    seeds = sorted(os.listdir(os.path.join(args.ingest, "seeds")))
    for name in seeds:
        with open(os.path.join(seed_dir, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(sanitize(os.path.join(args.ingest, "seeds", name)))

    by_target = report.get("entry_points_by_target", {})
    lines = []
    lines.append(f"# Per-title recompilation config for {args.title}.")
    lines.append("#")
    lines.append("# Addresses and reasoning only: no ROM bytes and no dump fingerprints.")
    lines.append("# Generated by tools/stage_title_config.py from a local coverage")
    lines.append("# ingest; regenerate with pkmn_bankgen after a new ingest.")
    lines.append("")
    lines.append("[title]")
    lines.append(f'id = "{args.title}"')
    lines.append(f'seed_dir = "{args.title}/seeds"')
    lines.append("")
    lines.append("# Every load base a bank must exist for. A base is")
    lines.append("# guest_span_start - module_span_start in the finding, so the same")
    lines.append("# image is recompiled again at each base; no dumped bytes are involved.")
    for finding in report.get("rom_alias_findings", []):
        cpu = finding["cpu"]
        lines.append("")
        lines.append("[[alias]]")
        lines.append(f'cpu          = "{cpu}"')
        lines.append(f'image        = "{finding["module"]}"')
        lines.append(f'load_address = {finding["resident_base"]}')
        lines.append(f'declared     = {finding["declared_base"]}')
        lines.append(f'pages        = {finding["pages"]}')
        lines.append(f'guest_span   = "{finding["guest_span"]}"')
        lines.append(f'module_span  = "{finding["module_span"]}"')
        lines.append(f'note         = "{finding["note"]}"')
    lines.append("")
    lines.append("[seeds]")
    for target, count in sorted(by_target.items()):
        lines.append(f'"{target}" = {count}')
    lines.append("")

    index = os.path.join(args.out, args.title + ".toml")
    with open(index, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print(f"wrote {index}")
    for name in seeds:
        print(f"  {args.title}/seeds/{name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
